class apb_environment;

    // =====================================================
    // MAILBOXES
    // =====================================================

    mailbox gen2drv;
    mailbox mon2scb;


    // =====================================================
    // VIRTUAL INTERFACE
    // =====================================================

    virtual apb_if vif;


    // =====================================================
    // COMPONENTS
    // =====================================================

    apb_generator  gen;
    apb_driver     drv;
    apb_monitor    mon;
    apb_scoreboard scb;


    // =====================================================
    // CONFIGURATION
    // =====================================================

    int num_transactions;


    // =====================================================
    // CONSTRUCTOR
    // =====================================================

    function new(
        virtual apb_if vif,
        int num_transactions
    );

        this.vif = vif;
        this.num_transactions = num_transactions;


        // -------------------------------------------------
        // Create mailboxes
        // -------------------------------------------------

        gen2drv = new();

        mon2scb = new();


        // -------------------------------------------------
        // Create generator
        // -------------------------------------------------

        gen = new(
            gen2drv,
            num_transactions
        );


        // -------------------------------------------------
// Create driver
// -------------------------------------------------

drv = new(
    gen2drv,
    vif
);


// -------------------------------------------------
// Create monitor
// -------------------------------------------------

mon = new(
    mon2scb,
    vif
);


// -------------------------------------------------
// Create scoreboard
// -------------------------------------------------

scb = new(
    mon2scb
);

    endfunction


    // =====================================================
    // RUN
    // =====================================================

    task run();

        fork

            gen.run();

            drv.run();

            mon.run();

            scb.run();

        join_none

    endtask


    // =====================================================
    // REPORT
    // =====================================================

    function void report();

        scb.report();

        mon.report_coverage();

    endfunction

endclass
