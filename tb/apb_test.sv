module apb_test;

    // =====================================================
    // CONFIGURATION
    // =====================================================

    parameter int NUM_TRANSACTIONS = 100;


    // =====================================================
    // CLOCK
    // =====================================================

    logic clk;


    // =====================================================
    // APB INTERFACE
    // =====================================================

    apb_if vif();


    // =====================================================
    // CONNECT CLOCK
    // =====================================================

    assign vif.PCLK = clk;


    // =====================================================
    // DUT
    // =====================================================

    apb_slave dut (

        .PCLK    (vif.PCLK),
        .PRESETn (vif.PRESETn),

        .PSEL    (vif.PSEL),
        .PENABLE (vif.PENABLE),
        .PWRITE  (vif.PWRITE),

        .PADDR   (vif.PADDR),
        .PWDATA  (vif.PWDATA),
        .PRDATA  (vif.PRDATA),

        .PREADY  (vif.PREADY),
        .PSLVERR (vif.PSLVERR)

    );


    // =====================================================
    // ENVIRONMENT
    // =====================================================

    apb_environment env;


    // =====================================================
    // CLOCK GENERATION
    // =====================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =====================================================
    // TEST
    // =====================================================

    initial begin

        // -------------------------------------------------
        // Create environment
        // -------------------------------------------------

        env = new(
            vif,
            NUM_TRANSACTIONS
        );


        // -------------------------------------------------
        // Initial values
        // -------------------------------------------------

        vif.PRESETn = 1'b0;


        // -------------------------------------------------
        // Reset
        // -------------------------------------------------

        repeat (3)
            @(posedge clk);


        // -------------------------------------------------
        // Release reset
        // -------------------------------------------------

        vif.PRESETn = 1'b1;


        // -------------------------------------------------
        // Start environment
        // -------------------------------------------------

        env.run();


        // -------------------------------------------------
        // Wait for testbench activity
        // -------------------------------------------------

        #10000;


        // -------------------------------------------------
        // Print scoreboard report
        // -------------------------------------------------

        env.report();


        // -------------------------------------------------
        // Finish simulation
        // -------------------------------------------------

        $finish;

    end

endmodule
